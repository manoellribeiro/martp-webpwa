// Generates src/lib/translations/android/*.ts from the Android app's strings.xml files,
// so both projects share the same texts. Run with `pnpm strings:sync [path-to-map-arts]`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const androidProject = resolve(
	process.argv[2] ?? process.env.MARTP_ANDROID_PATH ?? join(root, '../martp/map-arts')
);
const resDir = join(androidProject, 'app/src/main/res');
const outDir = join(root, 'src/lib/translations/android');

// Android resource folder -> BCP 47 language tag used on the web.
const locales = {
	values: 'en',
	'values-de': 'de',
	'values-es': 'es',
	'values-fr': 'fr',
	'values-pt-rBR': 'pt-BR'
};

const xmlEntities = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&apos;': "'" };

// Android's string resource rules: backslash escapes (\n, \t, \uXXXX, \' ...), unescaped
// double quotes are removed and keep the whitespace between them, and whitespace written
// literally elsewhere collapses to one space and is trimmed at the ends.
function unescape(value) {
	const xml = value.replace(/&(amp|lt|gt|quot|apos);/g, (entity) => xmlEntities[entity]);
	let result = '';
	let quoted = false;
	// Collapsed spaces wait here, so trailing ones are dropped and leading ones never start.
	let pendingSpace = false;
	const append = (text) => {
		if (pendingSpace && result) result += ' ';
		pendingSpace = false;
		result += text;
	};
	for (let i = 0; i < xml.length; i++) {
		const char = xml[i];
		if (char === '\\') {
			const next = xml[++i];
			if (next === 'u' && /^[0-9a-fA-F]{4}$/.test(xml.slice(i + 1, i + 5))) {
				append(String.fromCharCode(Number.parseInt(xml.slice(i + 1, i + 5), 16)));
				i += 4;
			} else if (next === 'n') append('\n');
			else if (next === 't') append('\t');
			else if (next !== undefined) append(next);
		} else if (char === '"') {
			quoted = !quoted;
		} else if (/\s/.test(char) && !quoted) {
			pendingSpace = true;
		} else {
			append(char);
		}
	}
	return result;
}

function parseStrings(file) {
	const xml = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
	const strings = {};
	for (const [, name, value] of xml.matchAll(/<string\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) {
		strings[name] = unescape(value);
	}
	return strings;
}

if (!existsSync(join(resDir, 'values/strings.xml'))) {
	console.error(`Android strings not found under ${resDir}`);
	process.exit(1);
}

mkdirSync(outDir, { recursive: true });
const english = parseStrings(join(resDir, 'values/strings.xml'));

for (const [folder, locale] of Object.entries(locales)) {
	const strings = parseStrings(join(resDir, folder, 'strings.xml'));
	const unknown = Object.keys(strings).filter((key) => !(key in english));
	if (unknown.length) console.warn(`${locale}: keys missing from English: ${unknown.join(', ')}`);

	const body = Object.entries(strings)
		.map(([key, value]) => `\t${key}: ${JSON.stringify(value)}`)
		.join(',\n');
	writeFileSync(
		join(outDir, `${locale}.ts`),
		`// GENERATED by scripts/sync-android-strings.mjs from res/${folder}/strings.xml. Do not edit.\n` +
			`export default {\n${body}\n} as const;\n`
	);
	console.log(`${locale}: ${Object.keys(strings).length} strings`);
}
